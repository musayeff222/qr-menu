function buildTheme(d: ConceptDim): MenuTemplateTheme {
  const fontPair: FontPairKey = "montserrat-inter";
  const customFonts = FONT_STACKS[d.fontI % FONT_STACKS.length]!;

  const common = {
    fontPair,
    headingWeight: d.headingWeight,
    radius: d.radius,
    cardStyle: d.cardStyle,
    heroVariant: d.heroVariant,
    categoryNav: d.categoryNav,
    density: d.density,
    showFab: d.showFab,
    showBottomNav: d.showBottomNav,
    overlayPercent: d.overlayPercent,
    productImageRadius: d.productImageRadius,
    heroPattern: d.heroPattern,
    headerLayout: d.headerLayout,
    productLayout: d.productLayout,
    iconStyle: d.iconStyle,
    renderMode: d.slug,
    customFonts,
  } satisfies Partial<MenuTemplateTheme>;

  if (d.tone === "luxury") {
    return {
      ...common,
      primary: hsl(43, 78, 44 + (d.hue % 6)),
      secondary: hsl(38, 32, 16),
      accent: hsl(36, 85, 58),
      background: hsl(0, 0, 5 + (d.hue % 4)),
      surface: hsl(35, 8, 10),
      text: hsl(42, 25, 96),
      muted: hsl(40, 10, 62),
    } as MenuTemplateTheme;
  }

  if (d.tone === "dark") {
    const h = d.hue;
    return {
      ...common,
      primary: hsl(h, 72, 58),
      secondary: hsl(h, 12, 18),
      accent: hsl((h + 145) % 360, 62, 55),
      background: hsl(222, 16, 7),
      surface: hsl(222, 14, 11),
      text: hsl(210, 25, 96),
      muted: hsl(217, 12, 58),
    } as MenuTemplateTheme;
  }

  if (d.tone === "neon") {
    return {
      ...common,
      primary: "#22d3ee",
      secondary: "#4c1d95",
      accent: "#f472b6",
      background: "#030712",
      surface: "#0f172a",
      text: "#f8fafc",
      muted: "#94a3b8",
    } as MenuTemplateTheme;
  }

  if (d.tone === "pastel") {
    const h = d.hue;
    return {
      ...common,
      primary: hsl(h, 45, 55),
      secondary: hsl((h + 40) % 360, 35, 88),
      accent: hsl((h + 200) % 360, 42, 62),
      background: hsl(h, 38, 97),
      surface: hsl(0, 0, 100),
      text: hsl(h, 22, 22),
      muted: hsl(h, 12, 48),
    } as MenuTemplateTheme;
  }

  if (d.tone === "warm") {
    const h = 24 + (d.hue % 12);
    return {
      ...common,
      primary: hsl(h, 55, 34),
      secondary: hsl(h, 38, 88),
      accent: hsl((h + 300) % 360, 50, 48),
      background: hsl(h, 48, 95),
      surface: hsl(35, 60, 99),
      text: hsl(h, 45, 16),
      muted: hsl(h, 16, 42),
    } as MenuTemplateTheme;
  }

  const h = d.hue;
  return {
    ...common,
    primary: hsl(h, 72, 44),
    secondary: hsl(h, 35, 91),
    accent: hsl((h + 48) % 360, 68, 48),
    background: hsl(h, 28, 97),
    surface: "#ffffff",
    text: hsl(h, 35, 12),
    muted: hsl(h, 14, 42),
  } as MenuTemplateTheme;
}

