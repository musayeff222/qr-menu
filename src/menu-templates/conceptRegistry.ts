function assertLength50() {
  if (CONCEPTS.length !== 50) {
    throw new Error(`conceptRegistry: expected 50 concepts, got ${CONCEPTS.length}`);
  }
  if (MENU_TEMPLATE_IDS_ORDERED.length !== 50) {
    throw new Error(`planTemplatePolicy expects 50 ids, got ${MENU_TEMPLATE_IDS_ORDERED.length}`);
  }
}

export function buildConceptMenuTemplates(): MenuTemplateDef[] {
  assertLength50();
  return MENU_TEMPLATE_IDS_ORDERED.map((id, i) => {
    const c = CONCEPTS[i]!;
    const theme = buildTheme(c);
    const category = CATEGORY_OF_INDEX(i);
    return {
      id,
      name: c.name,
      category,
      description: `${c.slug} · ${theme.headerLayout} · ${theme.productLayout} · ${theme.heroVariant}`,
      heroImage: HERO_IMAGES[i]!,
      theme,
    };
  });
}
